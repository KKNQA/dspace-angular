/**
 * KNQA: apply the KNQA theme's i18n labels to the core language files with a minimal diff.
 *
 * Source of truth: src/themes/knqa/assets/i18n/<lang>.json5
 * Target:          src/assets/i18n/<lang>.json5 (generated — never edit KNQA labels there)
 *
 * Unlike DSpace's `merge-i18n` script (which re-serializes the whole file and drops every
 * upstream comment), this script:
 *   - rewrites only the value of each overridden label, in place, keeping upstream comments
 *     and formatting, so upstream merges stay small;
 *   - appends labels that do not exist upstream (e.g. home.knqa.*) in a single marked block
 *     at the end of the file, replacing any previous block.
 * Running it twice produces the same file.
 *
 * Usage:
 *   npx ts-node --project ./tsconfig.ts-node.json scripts/knqa-i18n.ts          # apply
 *   npx ts-node --project ./tsconfig.ts-node.json scripts/knqa-i18n.ts --check  # verify only
 *
 * --check exits non-zero when the core file is out of date with the theme file, or when a
 * theme override no longer matches any upstream label (upstream renamed or removed it).
 *
 * After an upstream merge: take upstream's src/assets/i18n/*.json5, run this script, commit.
 */
import * as fs from 'fs';
import * as path from 'path';

const JSON5 = require('json5');

const THEME_DIR = path.join(__dirname, '..', 'src', 'themes', 'knqa', 'assets', 'i18n');
const CORE_DIR = path.join(__dirname, '..', 'src', 'assets', 'i18n');
const BLOCK_START = '  // ===== KNQA labels (generated by scripts/knqa-i18n.ts from src/themes/knqa/assets/i18n — do not edit here) =====';
const BLOCK_END = '  // ===== end KNQA labels =====';

const check = process.argv.includes('--check');
let failed = false;

for (const file of fs.readdirSync(THEME_DIR).filter((f) => f.endsWith('.json5'))) {
  const corePath = path.join(CORE_DIR, file);
  if (!fs.existsSync(corePath)) {
    console.error(`${file}: no core language file to apply to`);
    failed = true;
    continue;
  }
  const theme: Record<string, string> = JSON5.parse(fs.readFileSync(path.join(THEME_DIR, file), 'utf8'));
  const original = fs.readFileSync(corePath, 'utf8');
  const eol = original.includes('\r\n') ? '\r\n' : '\n';
  const { text, missingUpstream } = apply(original.split(/\r?\n/), theme, eol);

  if (missingUpstream.length) {
    console.warn(`${file}: ${missingUpstream.length} override(s) not found upstream (added to the KNQA block instead):`);
    missingUpstream.forEach((k) => console.warn(`  - ${k}`));
  }
  if (check) {
    if (text !== original) {
      console.error(`${file}: core file is out of date — run scripts/knqa-i18n.ts`);
      failed = true;
    }
    if (missingUpstream.length) {
      failed = true;
    }
  } else if (text !== original) {
    fs.writeFileSync(corePath, text, 'utf8');
    console.log(`${file}: updated`);
  } else {
    console.log(`${file}: already up to date`);
  }
}
process.exit(failed ? 1 : 0);

/**
 * Replace overridden values in place, then rebuild the KNQA block before the closing brace.
 * Keys whose name contains ".knqa." are KNQA additions and always live in the block.
 */
function apply(lines: string[], theme: Record<string, string>, eol: string) {
  // Drop a previously generated block so the result is idempotent
  const start = lines.indexOf(BLOCK_START);
  const end = lines.indexOf(BLOCK_END);
  if (start !== -1 && end > start) {
    lines.splice(start, end - start + 1);
    while (start > 0 && lines[start - 1].trim() === '') {
      lines.splice(start - 1, 1);
    }
  }

  const remaining = new Set(Object.keys(theme).filter((k) => !k.includes('.knqa.')));
  const missingUpstream: string[] = [];
  const keyLine = /^(\s*)"((?:[^"\\]|\\.)*)"(\s*:\s*)"(?:[^"\\]|\\.)*"(,?)(\s*)$/;
  for (let i = 0; i < lines.length; i++) {
    const m = keyLine.exec(lines[i]);
    if (m && remaining.has(m[2])) {
      lines[i] = `${m[1]}"${m[2]}"${m[3]}${JSON.stringify(theme[m[2]])}${m[4]}${m[5]}`;
      remaining.delete(m[2]);
    }
  }
  remaining.forEach((k) => missingUpstream.push(k));

  const blockKeys = Object.keys(theme).filter((k) => k.includes('.knqa.') || remaining.has(k));
  let close = lines.length - 1;
  while (close >= 0 && lines[close].trim() !== '}') {
    close--;
  }
  if (blockKeys.length) {
    // Make sure the last upstream entry ends with a comma before appending
    let last = close - 1;
    while (last >= 0 && (lines[last].trim() === '' || lines[last].trim().startsWith('//'))) {
      last--;
    }
    if (last >= 0 && !lines[last].trimEnd().endsWith(',') && !lines[last].trimEnd().endsWith('{')) {
      lines[last] = lines[last].trimEnd() + ',';
    }
    const block = ['', BLOCK_START, ...blockKeys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(theme[k])},`), BLOCK_END];
    lines.splice(close, 0, ...block);
  }
  return { text: lines.join(eol), missingUpstream };
}
